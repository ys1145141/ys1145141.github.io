def solve_x():
    """
    原理：
        目标：x³ × 0.995² × 0.99² = 1.01⁷
        所以：x = (1.01⁷ / (0.995² × 0.99²))^(1/3)
    """
    import math
    # 直接计算精确解
    x = (1.01**7 / (0.995**2 * 0.99**2)) ** (1/3)
    # 向上取整到千分位
    return math.ceil(x * 1000) / 1000


# 求解并输出
x = solve_x()
print(f"周一到周三每天需进步: {(x-1)*100:.3f}%")

# 验证
result = x**3 * 0.995**2 * 0.99**2
target = 1.01**7
print(f"验证: {result:.6f} >= {target:.6f} ? {result >= target}")
